(ns worldofcake.laylagen.rack-metadata-generate
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [clojure.string :as str]))

(defn- parse-args [args]
  (loop [remaining args options {}]
    (if (empty? remaining)
      options
      (let [[flag & tail] remaining]
        (if (= flag "--check")
          (recur tail (assoc options flag true))
          (let [[value & more] tail]
            (when-not value
              (throw (ex-info (str "Missing value for " flag) {})))
            (recur more (assoc options flag value))))))))

(defn- output-entries [metadata]
  (for [group (get-in metadata [:patch-bay :groups])
        output (:outputs group)]
    output))

(defn- cpp-string [value]
  (-> (str value)
      (str/replace "\\" "\\\\")
      (str/replace "\"" "\\\"")))

(defn- generated-class-name [metadata]
  (str (get-in metadata [:module :slug]) "RackOutputsGenerated"))

(defn- render-header [metadata]
  (let [app (name (:app metadata))
        outputs (vec (output-entries metadata))]
    (str "// Generated by WorldOfCake rack metadata. Do not edit directly.\n"
         "#pragma once\n\n"
         "namespace worldofcake\n"
         "{\n"
         "    namespace rack\n"
         "    {\n"
         "        namespace " app "\n"
         "        {\n"
         "            constexpr int kOutputCount = " (count outputs) ";\n"
         "            constexpr const char* kOutputLabels[kOutputCount] =\n"
         "            {\n"
         (apply str
                (map-indexed (fn [index output]
                               (str "                \"" (cpp-string (:config-label output)) "\""
                                    (when (< index (dec (count outputs))) ",") "\n"))
                             outputs))
         "            };\n"
         "        } // namespace " app "\n"
         "    } // namespace rack\n"
         "} // namespace worldofcake\n")))

(defn- generated-path [metadata]
  (let [app (name (:app metadata))
        slug (get-in metadata [:module :slug])]
    (str "worldofcake/generated/rack/" app "/" slug "RackOutputsGenerated.h")))

(defn- safe-output-file [output-dir relative]
  (let [root (.getCanonicalFile (io/file output-dir))
        target (.getCanonicalFile (io/file root relative))
        root-path (str (.getPath root) java.io.File/separator)]
    (when-not (str/starts-with? (.getPath target) root-path)
      (throw (ex-info "Generated output path escapes output directory" {:path relative})))
    target))

(defn -main [& args]
  (try
    (let [options (parse-args args)
          metadata-path (get options "--metadata")
          output-dir (get options "--output")
          check? (contains? options "--check")]
      (when-not (and metadata-path output-dir)
        (throw (ex-info "Usage: rack-metadata-generate --metadata FILE --output DIRECTORY [--check]" {})))
      (let [metadata (edn/read-string (slurp metadata-path))
            relative (generated-path metadata)
            target (safe-output-file output-dir relative)
            content (render-header metadata)]
        (if check?
          (when-not (and (.isFile target) (= content (slurp target)))
            (throw (ex-info (str "Generated Rack metadata is stale: " relative) {})))
          (do
            (.mkdirs (.getParentFile target))
            (spit target content)))
        (println (if check? "Checked" "Generated") relative)))
    (catch Exception e
      (binding [*out* *err*]
        (println "Rack metadata generation failed:" (.getMessage e)))
      (System/exit 1))))
